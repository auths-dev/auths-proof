#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct FormalEvidence {
    kind: FormalEvidenceKind,
    artifact: String,
    /// SHA-256 of the artifact's bytes.
    ///
    /// Evidence used to be EXISTENCE-CHECKED only: the audit confirmed a file
    /// was present at the path and read nothing. An artifact could be emptied,
    /// rewritten, or replaced wholesale and every claim citing it still passed.
    ///
    /// Mandatory. Update mode computes it; check mode verifies it. An evidence
    /// entry is never permitted to exist in an unhashed intermediate state.
    sha256: String,
}

#[derive(Clone, Copy, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "kebab-case")]
enum FormalEvidenceKind {
    LeanProof,
    LeanRefinement,
    MechanicalTranslation,
    TranslatedRust,
    SourceClosure,
    LeanGeneratedVectors,
    MutationMatrix,
    TestCorpus,
}

impl FormalEvidenceKind {
    fn validates_path(self, path: &str) -> bool {
        match self {
            Self::LeanProof | Self::LeanRefinement => path.ends_with(".lean"),
            Self::MechanicalTranslation | Self::TranslatedRust => {
                path.starts_with("formal/qualification/aeneas/generated/")
                    && path.ends_with(".lean")
            }
            Self::SourceClosure => path == "formal/qualification/aeneas/source-closure.json",
            Self::LeanGeneratedVectors => {
                path.starts_with("core/formal-vectors/v1/") && path.ends_with(".json")
            }
            Self::MutationMatrix => path == "formal/refinement-mutations-v1.json",
            Self::TestCorpus => !path.trim().is_empty(),
        }
    }
}

fn validated_evidence_path(relative: &str) -> Result<PathBuf, String> {
    let path = Path::new(relative);
    if path.is_absolute()
        || path
            .components()
            .any(|component| !matches!(component, std::path::Component::Normal(_)))
    {
        return Err(format!(
            "evidence path must be a normalized workspace-relative path: {relative}"
        ));
    }
    let unresolved = root().join(path);
    let metadata = fs::symlink_metadata(&unresolved)
        .map_err(|error| format!("could not stat evidence {}: {error}", unresolved.display()))?;
    if !metadata.file_type().is_file() || metadata.file_type().is_symlink() {
        return Err(format!(
            "evidence path is not a regular non-symlink file: {relative}"
        ));
    }
    let workspace = fs::canonicalize(root())
        .map_err(|error| format!("could not resolve workspace root: {error}"))?;
    let resolved = fs::canonicalize(&unresolved).map_err(|error| {
        format!(
            "could not resolve evidence {}: {error}",
            unresolved.display()
        )
    })?;
    if !resolved.starts_with(&workspace) {
        return Err(format!("evidence path escapes workspace: {relative}"));
    }
    Ok(resolved)
}

fn validate_sha256(value: &str) -> Result<(), String> {
    if value.len() == 64
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    {
        Ok(())
    } else {
        Err(format!("invalid lowercase SHA-256 {value}"))
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct LeanAssuranceAudit {
    schema: String,
    declarations: Vec<LeanAssuranceDeclaration>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct LeanAssuranceDeclaration {
    name: String,
    module: String,
    kind: String,
    statement: String,
    axioms: Vec<String>,
    statement_constants: Vec<String>,
}

fn lean_statement_inventory_sha256(audit: &LeanAssuranceAudit) -> String {
    let mut declarations = audit.declarations.iter().collect::<Vec<_>>();
    declarations.sort_by(|left, right| left.name.cmp(&right.name));
    let mut digest = Sha256::new();
    for declaration in declarations {
        let mut axioms = declaration.axioms.clone();
        axioms.sort();
        for value in [
            declaration.name.as_str(),
            declaration.module.as_str(),
            declaration.kind.as_str(),
            declaration.statement.as_str(),
        ] {
            digest.update(value.as_bytes());
            digest.update([0]);
        }
        for axiom in axioms {
            digest.update(axiom.as_bytes());
            digest.update([0]);
        }
        let mut constants = declaration.statement_constants.clone();
        constants.sort();
        digest.update([0xfe]);
        for constant in constants {
            digest.update(constant.as_bytes());
            digest.update([0]);
        }
        digest.update([0xff]);
    }
    hex::encode(digest.finalize())
}

pub(crate) fn formal_assurance_audit(formal_root: &Path, update: bool) -> Result<(), String> {
    let manifest_path = formal_root.join("assurance-manifest-v1.toml");
    let mut manifest: FormalAssuranceManifest = toml::from_str(
        &fs::read_to_string(&manifest_path)
            .map_err(|error| format!("could not read {}: {error}", manifest_path.display()))?,
    )
    .map_err(|error| {
        format!(
            "invalid assurance manifest {}: {error}",
            manifest_path.display()
        )
    })?;
    if manifest.schema != "auths-proof-formal-assurance/v1" {
        return Err(format!(
            "unsupported formal assurance schema {}",
            manifest.schema
        ));
    }

    let lean_toolchain_path = formal_root.join("lean-toolchain");
    let lean_toolchain = fs::read_to_string(&lean_toolchain_path)
        .map_err(|error| format!("could not read {}: {error}", lean_toolchain_path.display()))?;
    if lean_toolchain.trim() != manifest.lean_toolchain {
        return Err("formal assurance manifest Lean toolchain drifted".to_owned());
    }

    let toolchain_lock_path = formal_root.join("translation-toolchain.lock");
    let toolchain_lock_digest = sha256_file(&toolchain_lock_path)?;
    if manifest.toolchain_lock_sha256 != toolchain_lock_digest {
        return Err(format!(
            "formal toolchain lock drifted: expected {}, found {toolchain_lock_digest}",
            manifest.toolchain_lock_sha256
        ));
    }

    let audit_output = command_output_in(
        "lake",
        &["env", "lean", "Auths/AssuranceAudit.lean"],
        formal_root,
        None,
    )?;
    let audit: LeanAssuranceAudit = serde_json::from_str(audit_output.trim())
        .map_err(|error| format!("compiled Lean assurance audit emitted invalid JSON: {error}"))?;
    if audit.schema != "auths-proof-lean-assurance-audit/v1" {
        return Err(format!(
            "unsupported compiled Lean assurance audit schema {}",
            audit.schema
        ));
    }
    let statement_inventory_sha256 = lean_statement_inventory_sha256(&audit);
    if manifest.statement_review.trim().is_empty() {
        return Err("formal assurance statement review batch is empty".to_owned());
    }
    if manifest.statement_inventory_sha256 != statement_inventory_sha256 {
        return Err(format!(
            "compiled Lean statement inventory is not explicitly reviewed: manifest binds {}, compiled audit is {statement_inventory_sha256}; review the complete audit, change statement_review, and set statement_inventory_sha256 explicitly before update",
            manifest.statement_inventory_sha256
        ));
    }

    if update {
        synchronize_formal_assurance_manifest(
            formal_root,
            &manifest_path,
            &mut manifest,
            &audit,
            &toolchain_lock_digest,
        )?;
    }

    let allowed_axioms: BTreeSet<_> = manifest.allowed_axioms.iter().cloned().collect();
    if allowed_axioms.len() != manifest.allowed_axioms.len() || allowed_axioms.contains("sorryAx") {
        return Err("formal assurance axiom allowlist is duplicate or permits sorryAx".to_owned());
    }

    let mut compiled = BTreeMap::new();
    for declaration in audit.declarations {
        let name = declaration.name.clone();
        if compiled.insert(name.clone(), declaration).is_some() {
            return Err(format!(
                "compiled Lean assurance audit repeated declaration {name}"
            ));
        }
    }
    let expected_source_closure = semantic_source_closure_paths(formal_root)?;
    let expected_closure_digest = semantic_source_closure_digest(&expected_source_closure)?;
    let mut reviewed = BTreeSet::new();
    let mut claim_ids = BTreeSet::new();
    for claim in &manifest.claims {
        if !claim_ids.insert(claim.claim_id.clone()) {
            return Err(format!(
                "formal assurance manifest repeated claim id {}",
                claim.claim_id
            ));
        }
        if !reviewed.insert(claim.lean_declaration.clone()) {
            return Err(format!(
                "formal assurance manifest repeated declaration {}",
                claim.lean_declaration
            ));
        }
        for (field, value) in [
            ("claim_id", claim.claim_id.as_str()),
            ("claim_text", claim.claim_text.as_str()),
            ("formal_review", claim.formal_review.as_str()),
            ("scope", claim.scope.as_str()),
        ] {
            if value.trim().is_empty() {
                return Err(format!(
                    "formal claim {} has empty {field}",
                    claim.lean_declaration
                ));
            }
        }
        if claim.formal_review != manifest.statement_review {
            return Err(format!(
                "formal claim {} review tag does not match reviewed statement batch {}",
                claim.lean_declaration, manifest.statement_review
            ));
        }
        if !matches!(
            claim.claim_status.as_str(),
            "proved" | "qualified" | "assumed"
        ) {
            return Err(format!(
                "formal claim {} has unsupported status {}",
                claim.lean_declaration, claim.claim_status
            ));
        }
        if let Some((metadata, translation_artifact)) =
            qualified_refinement_metadata(&claim.lean_declaration)
        {
            let expected_symbols = metadata
                .rust_symbols
                .iter()
                .map(|symbol| (*symbol).to_owned())
                .collect::<Vec<_>>();
            let expected_residual = metadata
                .residual_assumptions
                .iter()
                .map(|assumption| (*assumption).to_owned())
                .collect::<Vec<_>>();
            if claim.claim_status != "qualified"
                || claim.claim_text != metadata.claim_text
                || claim.rust_symbols != expected_symbols
                || claim.scope != metadata.scope
                || claim.residual_assumptions != expected_residual
            {
                return Err(format!(
                    "formal claim {} production refinement metadata drifted from the executable boundary table",
                    claim.lean_declaration
                ));
            }
            validate_production_evidence(
                &claim.lean_declaration,
                &claim.evidence,
                metadata.translation_evidence_kind,
                translation_artifact,
            )?;
        }
        if claim.toolchain_lock_sha256 != toolchain_lock_digest {
            return Err(format!(
                "formal claim {} has stale toolchain lock digest",
                claim.lean_declaration
            ));
        }
        if claim.semantic_source_closure.is_empty()
            || claim.evidence.is_empty()
            || claim.residual_assumptions.is_empty()
        {
            return Err(format!(
                "formal claim {} must declare source closure, evidence, and residual assumptions",
                claim.lean_declaration
            ));
        }
        if claim.semantic_source_closure != expected_source_closure {
            return Err(format!(
                "formal claim {} semantic source closure is not the Lean-resolved transitive assurance closure",
                claim.lean_declaration
            ));
        }
        let closure_digest = &expected_closure_digest;
        if *closure_digest != claim.semantic_source_closure_sha256 {
            return Err(format!(
                "formal claim {} semantic source closure drifted: expected {}, found {closure_digest}",
                claim.lean_declaration, claim.semantic_source_closure_sha256
            ));
        }
        for symbol in &claim.rust_symbols {
            if symbol.trim().is_empty() {
                return Err(format!(
                    "formal claim {} contains an empty Rust symbol",
                    claim.lean_declaration
                ));
            }
        }
        let expected_proof =
            declaration_source_path(compiled.get(&claim.lean_declaration).ok_or_else(|| {
                format!(
                    "reviewed Lean declaration {} is absent from the compiled environment",
                    claim.lean_declaration
                )
            })?)?;
        let primary = claim
            .evidence
            .iter()
            .filter(|item| {
                matches!(
                    item.kind,
                    FormalEvidenceKind::LeanProof | FormalEvidenceKind::LeanRefinement
                )
            })
            .collect::<Vec<_>>();
        if primary.len() != 1 || primary[0].artifact != expected_proof {
            return Err(format!(
                "formal claim {} must cite exactly its defining Lean module {expected_proof} as primary proof evidence",
                claim.lean_declaration
            ));
        }
        for item in &claim.evidence {
            if item.artifact.trim().is_empty() || !item.kind.validates_path(&item.artifact) {
                return Err(format!(
                    "formal claim {} contains incomplete or kind/path-mismatched evidence {}",
                    claim.lean_declaration, item.artifact
                ));
            }
            let artifact = validated_evidence_path(&item.artifact)?;
            validate_mutation_witnesses(&artifact, &compiled)?;
            validate_sha256(&item.sha256).map_err(|error| {
                format!(
                    "formal claim {} evidence {} has {error}",
                    claim.lean_declaration, item.artifact
                )
            })?;
            let bytes = fs::read(&artifact).map_err(|error| {
                format!("could not read evidence {}: {error}", artifact.display())
            })?;
            let actual = hex::encode(Sha256::digest(&bytes));
            if actual != item.sha256 {
                return Err(format!(
                    "formal claim {} cites evidence {} with digest {}, \
                     but the artifact hashes to {actual}",
                    claim.lean_declaration, item.artifact, item.sha256
                ));
            }
        }

        let declaration = compiled.get(&claim.lean_declaration).ok_or_else(|| {
            format!(
                "reviewed Lean declaration {} is absent from the compiled environment",
                claim.lean_declaration
            )
        })?;
        if declaration.kind != "theorem" {
            return Err(format!(
                "reviewed declaration {} is {}, not theorem",
                claim.lean_declaration, declaration.kind
            ));
        }
        let statement_digest = hex::encode(Sha256::digest(declaration.statement.as_bytes()));
        if statement_digest != claim.lean_statement_sha256 {
            return Err(format!(
                "Lean statement drift for {}: expected {}, found {statement_digest}",
                claim.lean_declaration, claim.lean_statement_sha256
            ));
        }
        let actual_axioms: BTreeSet<_> = declaration.axioms.iter().cloned().collect();
        let reviewed_axioms: BTreeSet<_> = claim.axioms.iter().cloned().collect();
        if actual_axioms != reviewed_axioms {
            return Err(format!(
                "Lean axiom drift for {}: reviewed={reviewed_axioms:?}, compiled={actual_axioms:?}",
                claim.lean_declaration
            ));
        }
        if let Some(unapproved) = actual_axioms.difference(&allowed_axioms).next() {
            return Err(format!(
                "Lean declaration {} transitively depends on unapproved axiom {unapproved}",
                claim.lean_declaration
            ));
        }
    }

    // All claims have the identical, independently resolved path set. Hash it
    // once per snapshot, then reject mutation during the complete claim audit.
    if semantic_source_closure_digest(&expected_source_closure)? != expected_closure_digest {
        return Err("Lean semantic source closure changed during assurance audit".to_owned());
    }
    let compiled_names: BTreeSet<_> = compiled.keys().cloned().collect();
    if reviewed != compiled_names {
        return Err(format!(
            "compiled and reviewed Lean claim inventories differ: reviewed={reviewed:?}, compiled={compiled_names:?}"
        ));
    }
    let evidence_directory = root().join("target/formal");
    fs::create_dir_all(&evidence_directory).map_err(|error| {
        format!(
            "could not create formal evidence directory {}: {error}",
            evidence_directory.display()
        )
    })?;
    let mut evidence = serde_json::to_vec_pretty(
        &serde_json::from_str::<Value>(audit_output.trim())
            .map_err(|error| format!("could not normalize Lean assurance evidence: {error}"))?,
    )
    .map_err(|error| format!("could not encode Lean assurance evidence: {error}"))?;
    evidence.push(b'\n');
    fs::write(
        evidence_directory.join("lean-assurance-audit.json"),
        &evidence,
    )
    .map_err(|error| format!("could not write Lean assurance evidence: {error}"))?;
    let committed_audit = root().join(formal_coverage::AUDIT_PATH);
    if update {
        fs::write(&committed_audit, &evidence)
            .map_err(|error| format!("could not write {}: {error}", committed_audit.display()))?;
    } else if fs::read(&committed_audit).ok().as_deref() != Some(evidence.as_slice()) {
        return Err(format!(
            "{} differs from the compiled Lean assurance audit; run `cargo xtask formal --update`",
            formal_coverage::AUDIT_PATH
        ));
    }
    formal_coverage::synchronize_coverage(&root(), update)?;
    println!("Proof coverage:             committed measurement matches a fresh run");
    println!(
        "Formal assurance audit:     PASS ({} compiled statements; transitive axioms reviewed)",
        reviewed.len()
    );
    Ok(())
}

